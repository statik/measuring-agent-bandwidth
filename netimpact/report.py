def _html_spark(value: float, maximum: float) -> str:
    percent = _spark_percent(value, maximum)
    return (
        f'<td class="spark"><div class="track">'
        f'<div class="fill" style="width:{percent}%"></div></div></td>'
    )


def _html_downloads(results: dict) -> list[str]:
    groups = results["one_time"]["groups"]
    if not groups:
        return ['<div class="label">One-time downloads</div><div class="impact">None.</div>']
    maximum = max(row["aggregate_bytes"] for g in groups for row in g["items"])
    parts = []
    for group in groups:
        title = f"{group['group']} — {format_bytes(group['aggregate_bytes'])} total"
        parts.append(f'<div class="label">{_html_escape(title)}</div>')
        parts.append(
            '<table><tr><th>Item</th><th class="num">Size</th><th class="num">Students</th>'
            '<th class="num">Aggregate</th><th></th></tr>'
        )
        for row in group["items"]:
            parts.append(
                f"<tr><td>{_html_escape(row['name'])}<br>"
                f'<span class="note">{_html_escape(row["detail"])}</span></td>'
                f'<td class="num">{format_bytes(row["bytes_each"])}</td>'
                f'<td class="num">{row["downloads"]:g}</td>'
                f'<td class="count">{format_bytes(row["aggregate_bytes"])}</td>'
                f"{_html_spark(row['aggregate_bytes'], maximum)}</tr>"
            )
        parts.append("</table>")
    return parts


def _html_assistant(results: dict) -> list[str]:
    assistant = results["assistant"]
    parts = ['<div class="label">AI assistant traffic</div>']
    if not assistant["items"]:
        return [*parts, '<div class="impact">None modeled for this session.</div>']
    parts.append(
        '<table><tr><th>Activity</th><th class="num">Convs/student</th>'
        '<th class="num">Per conversation</th><th class="num">Per student</th>'
        '<th class="num">Room total</th></tr>'
    )
    for row in assistant["items"]:
        per_conversation = (
            row["uplink_bytes_per_conversation"] + row["downlink_bytes_per_conversation"]
        )
        parts.append(
            f"<tr><td>{_html_escape(row['name'])}</td>"
            f'<td class="num">{row["conversations_per_student"]}</td>'
            f'<td class="num">{format_bytes(per_conversation)}</td>'
            f'<td class="num">{format_bytes(row["bytes_per_student"])}</td>'
            f'<td class="count">{format_bytes(row["aggregate_bytes"])}</td></tr>'
        )
    parts.append("</table>")
    parts.append(
        f'<div class="note" style="margin-top:5px">Whole room, whole session: '
        f"{format_bytes(assistant['aggregate_bytes'])} — an average of "
        f"{assistant['average_mbps']:g} Mbps. "
        f"If every student's assistant streamed at the same instant: about "
        f"{assistant['all_streaming_at_once_mbps']:g} Mbps, less than one video call.</div>"
    )
    return parts


def _html_burst(results: dict) -> list[str]:
    burst = results["download_burst"]
    maximum = max(row["minutes"] for row in burst) if burst else 0
    goodput = int(results["assumptions"]["wifi_goodput_factor"] * 100)
    parts = [
        '<div class="label">Worst case — every student downloads everything '
        "at the venue, at once</div>",
        '<table><tr><th>Venue link</th><th class="num">All downloads complete in</th>'
        "<th></th></tr>",
    ]
    for row in burst:
        parts.append(
            f'<tr><td>{row["link_mbps"]} Mbps</td><td class="count">{row["minutes"]:g} min</td>'
            f"{_html_spark(row['minutes'], maximum)}</tr>"
        )
    parts.append("</table>")
    parts.append(
        f'<div class="note" style="margin-top:5px">Assumes {goodput}% of link speed as real-world '
        "Wi-Fi goodput. Staggering the install step or asking attendees to install before "
        "arriving removes this burst entirely.</div>"
    )
    return parts


def html_report(results: dict) -> str:
    """Render the aggregated results as a self-contained HTML fragment.

    Args:
        results: The dict produced by engine.summarize().

    Returns:
        An HTML fragment (styles included) matching the PDF layout.
    """
    workshop = results["workshop"]
    verdict = results["verdict"]
    one_time = results["one_time"]
    assistant = results["assistant"]
    meta = (
        f"{results['generated'][:10]} · {workshop['students']} students · "
        f"{workshop['duration_hours']:g}-hour session"
    )
    stats = (
        (format_bytes(one_time["aggregate_bytes"]), "One-time downloads"),
        (format_bytes(one_time["average_bytes_per_student"]), "Avg per student"),
        (format_bytes(assistant["aggregate_bytes"]), "Assistant, whole room"),
        (f"{assistant['average_mbps']:g} Mbps", "Assistant room average"),
        (f"{assistant['all_streaming_at_once_mbps']:g} Mbps", "All streams at once"),
    )
    stat_cells = "".join(
        f'<div class="stat"><b>{_html_escape(v)}</b><span>{_html_escape(label)}</span></div>'
        for v, label in stats
    )
    parts = [
        f"<style>{HTML_STYLE}</style>",
        '<div class="ni-report">',
        '<div class="titlebar">',
        f"<h1>Network Impact Report — {_html_escape(workshop['name'])}</h1>",
        f'<div class="meta">{_html_escape(meta)}<br>'
        f'<span class="verdict" style="color:{verdict["color"]}">'
        f"{_html_escape(verdict['label'])}</span></div>",
        "</div>",
        '<hr class="rule">',
        f'<div class="stats">{stat_cells}</div>',
        '<div class="label">Venue impact</div>',
        f'<div class="impact">{_html_escape(verdict["impact"])}</div>',
        *_html_downloads(results),
        *_html_assistant(results),
        *_html_burst(results),
        f'<div class="footer"><span>Generated by {_html_escape(results["tool"])} · '
        f"{results['generated'][:10]}</span><span>netimpact</span></div>",
        "</div>",
    ]
    return "\n".join(parts)
